function shotSet(script, episode) {
  const isComic = script.mode === "ai_manhua_drama";
  const baseZh = `${script.visualStyle}，第${episode.title}，竖屏构图，人物造型一致，表情细腻，光影参与叙事，前景遮挡，空间压迫，短剧强钩子，画面适合AI视频生产。`;
  const baseEn = `Vertical cinematic ${isComic ? "AI comic drama" : "live-action short drama"}, ${script.visualStyle}, consistent character design, expressive micro reactions, layered lighting, foreground obstruction, spatial pressure, strong short-drama hook, production-ready.`;
  return [
    ["压迫建立", "中近景缓慢推进，焦点从环境道具转到主角眼神。"],
    ["信息错位", "以前景遮挡制造窥视感，背景人物保持压低的反应。"],
    ["反打对峙", "长焦压缩空间，反打镜头强化双方权力关系。"],
    ["结尾钩子", "低机位停在关键证据或人物微表情上，留出一秒静默。"]
  ].map(([label, camera], index) => ({
    shot: index + 1,
    duration: "6-8秒",
    visual: `${label}。${isComic ? "漫画质感画面，线条和光斑强化情绪。" : "真实室内或密闭空间调度，演员站位形成压迫关系。"}`,
    camera,
    action: "主角没有立刻开口，先停半拍，手指收紧，眼神短暂闪避后重新抬起。",
    dialogue: index === 3 ? episode.endingHook : "你说得太顺了，像是早就知道我要问什么。",
    sound: "低频环境声、呼吸声、衣料摩擦，关键停顿处抽掉背景音乐。",
    emotion: `${label}服务于本集冲突，让观众感到关系和真相正在反转。`,
    aiPromptZh: baseZh,
    aiPromptEn: baseEn
  }));
}

